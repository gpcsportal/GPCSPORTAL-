<h1>GPCS Portal Privacy Notice</h1>
<p class="muted">Last updated: 18 September 2026</p>
<p>This notice explains the information used by GPCS Portal to provide student, faculty and administrator features.</p>
<h2>Information the portal uses</h2>
<ul>
<li>Registration details such as name, email, optional mobile number, college/branch details, address and optional profile photo.</li>
<li>Authentication and security information such as password hashes, session records, login timestamps and basic security logs.</li>
<li>Academic uploads and related metadata for Papers, Notes and Gallery submissions.</li>
<li>Contact messages and notices needed to operate portal features.</li>
</ul>
<h2>Why it is used</h2>
<p>The information is used to authenticate users, provide portal features, moderate uploads, respond to contact requests, protect the service, and maintain academic resources.</p>
<h2>Visibility</h2>
<p>Approved academic uploads and Gallery items can become visible to signed-in portal users. Account passwords are not displayed. Registration details are intended for portal administration and account operation rather than public display.</p>
<h2>Storage and retention</h2>
<p>Portal data is stored in the application's database and persistent upload storage. Records may be retained while needed for account operation, academic resources, moderation, security, or administrative requirements. Administrators can remove portal content where appropriate.</p>
<h2>Your responsibilities</h2>
<p>Do not upload unnecessary personal information in Papers, Notes, Gallery images, captions, or contact messages. If account information needs correction or removal, use the portal Contact option to reach the administrator.</p>
